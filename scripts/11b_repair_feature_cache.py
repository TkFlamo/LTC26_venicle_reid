#!/usr/bin/env python3
"""Repair caches produced by early v0.4 builds that stored metadata as dtype=object.

This command intentionally requires --allow-legacy-pickle because NumPy must use pickle
once to read the broken local cache. Use it only on a cache you generated yourself.
The rewritten output contains no object arrays and loads with allow_pickle=False.
"""
from __future__ import annotations

import argparse
from pathlib import Path
import numpy as np


def _is_safe_scalar(x) -> bool:
    return x is None or isinstance(x, (str, bytes, int, float, bool, np.generic))


def main():
    p = argparse.ArgumentParser()
    p.add_argument('--input', required=True)
    p.add_argument('--out', required=True)
    p.add_argument('--allow-legacy-pickle', action='store_true')
    a = p.parse_args()
    if not a.allow_legacy_pickle:
        raise SystemExit(
            'Refusing to load a pickle-backed legacy NPZ. Re-run with --allow-legacy-pickle '
            'only if this cache was generated by your own project.'
        )

    src = Path(a.input)
    dst = Path(a.out)
    with np.load(src, allow_pickle=True) as d:
        payload = {}
        repaired = []
        for key in d.files:
            arr = d[key]
            if arr.dtype == object:
                flat = arr.reshape(-1).tolist()
                if not all(_is_safe_scalar(x) for x in flat):
                    bad = next(type(x).__name__ for x in flat if not _is_safe_scalar(x))
                    raise RuntimeError(f'Unsafe/non-scalar object in key {key!r}: {bad}')
                # All object metadata in the feature cache contract is textual.
                arr = np.asarray([str(x) for x in flat], dtype=np.str_).reshape(arr.shape)
                repaired.append(key)
            payload[key] = arr

    dst.parent.mkdir(parents=True, exist_ok=True)
    np.savez_compressed(dst, **payload)
    with np.load(dst, allow_pickle=False) as check:
        for key in check.files:
            _ = check[key]
    print(f'repaired keys: {repaired or "none"}')
    print(dst)


if __name__ == '__main__':
    main()
